"""
Converts all Qt Designer .ui files in assets/ui/ to Python modules in src/ui/.

Output files are named <original_name>_ui.py and are generated by pyside6-uic.
They are excluded from version control — re-run this script after pulling changes
that modify any .ui file.

Usage:
    python build_ui.py
"""

import subprocess
import sys
from pathlib import Path

UI_SRC = Path("assets/ui")
UI_DST = Path("src/ui")

# Resolve pyside6-uic from the same Python environment that is running this
# script, so it works inside a venv without needing the venv to be on PATH.
_UIC = Path(sys.executable).parent / "pyside6-uic"
if sys.platform == "win32":
    _UIC = _UIC.with_suffix(".exe")


def main() -> None:
    if not _UIC.exists():
        print(f"pyside6-uic not found at {_UIC}")
        print("Run this script with the project venv active:  .venv\\Scripts\\python build_ui.py")
        sys.exit(1)

    ui_files = sorted(UI_SRC.glob("*.ui"))
    if not ui_files:
        print(f"No .ui files found in {UI_SRC}/")
        return

    UI_DST.mkdir(parents=True, exist_ok=True)
    errors = 0

    for ui_file in ui_files:
        out_file = UI_DST / f"{ui_file.stem}_ui.py"
        result = subprocess.run(
            [str(_UIC), str(ui_file), "-o", str(out_file)],
            capture_output=True,
            text=True,
        )
        if result.returncode == 0:
            print(f"  OK   {ui_file}  ->  {out_file}")
        else:
            print(f"  ERR  {ui_file}")
            print(f"       {result.stderr.strip()}")
            errors += 1

    print()
    if errors:
        print(f"{errors} file(s) failed.")
        sys.exit(1)
    else:
        print(f"{len(ui_files)} file(s) built successfully.")


if __name__ == "__main__":
    main()
